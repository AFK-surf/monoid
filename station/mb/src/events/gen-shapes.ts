// Writes shapes.mbt (node station/mb/src/events/gen-shapes.ts) from the client's shapes (client/core-ts/src/shapes/
// schema.ts SHAPES): of them, those a runtime can be named in (RuntimeKind, a Message's authorRuntime), which alone
// station/src/read/runtime-view.ts `runtimeView` changes, and of each only the fields and variants that can.
// station/test/mb-events.test.ts holds the file to what this makes now.
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import type { Shape, Ty } from "../../../../client/core-ts/src/shapes/dsl.ts";
import { SHAPES } from "../../../../client/core-ts/src/shapes/schema.ts";

/// The types a type names.
function refs(ty: Ty, out: Set<string>): void {
  if (typeof ty === "string") out.add(ty);
  else if ("opt" in ty) refs(ty.opt, out);
  else if ("vec" in ty) refs(ty.vec, out);
  else if ("map" in ty) refs(ty.map, out);
  else for (const t of ty.tuple) refs(t, out);
}

/// shapes.mbt's text, of `shapes`.
export function shapesMbt(shapes: Record<string, Shape> = SHAPES): string {
  const named = new Map<string, Set<string>>();
  for (const [name, s] of Object.entries(shapes)) {
    const o = new Set<string>();
    if (s.kind === "struct") for (const f of s.fields) refs(f.ty, o);
    if (s.kind === "tagged") for (const t of Object.values(s.variants)) refs(t, o);
    named.set(name, o);
  }
  // What a runtime can be named in, however deep.
  const bearing = new Set(["RuntimeKind", "Message"]);
  for (let more = true; more; ) {
    more = false;
    for (const [name, o] of named) {
      if (!bearing.has(name) && [...o].some((x) => bearing.has(x))) {
        bearing.add(name);
        more = true;
      }
    }
  }
  const bears = (ty: Ty) => {
    const o = new Set<string>();
    refs(ty, o);
    return [...o].some((x) => bearing.has(x));
  };
  const kept: Record<string, unknown> = {};
  for (const name of [...bearing].sort()) {
    const s = shapes[name];
    if (s === undefined || name === "RuntimeKind") continue;
    if (s.kind === "struct") kept[name] = { k: "s", f: s.fields.filter((f) => bears(f.ty)).map((f) => [f.name, f.ty]) };
    else if (s.kind === "tagged") kept[name] = { k: "t", tag: s.tag, c: s.content, v: Object.fromEntries(Object.entries(s.variants).filter(([, t]) => bears(t))) };
  }
  const entries = Object.entries(kept);
  const json = ["{", ...entries.map(([k, v], i) => ` ${JSON.stringify(k)}: ${JSON.stringify(v)}${i < entries.length - 1 ? "," : ""}`), "}"];
  return `// Generated by gen-shapes.ts from client/core-ts/src/shapes/schema.ts: the shapes a runtime can be named in, each with
// only what can name one (compat.mbt). Do not edit; made again by gen-shapes.ts beside this.

///|
let shapes_text : String =
${json.map((l) => `  #|${l}`).join("\n")}
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) writeFileSync(new URL("./shapes.mbt", import.meta.url), shapesMbt());
