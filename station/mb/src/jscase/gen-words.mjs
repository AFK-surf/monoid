// Writes words.mbt (node station/mb/src/jscase/gen-words.mjs station/mb/src/jscase/words.mbt) from this node's Unicode
// properties: the code points a regular expression's /[\p{L}\p{N}]/u takes, which split a text into its words.
import { writeFileSync } from "node:fs";
const out = [];
let start = -1;
for (let c = 0; c <= 0x110000; c++) {
  const ok = c <= 0x10ffff && !(c >= 0xd800 && c <= 0xdfff) && /[\p{L}\p{N}]/u.test(String.fromCodePoint(c));
  if (ok && start < 0) start = c;
  if (!ok && start >= 0) (out.push(start, c - 1), (start = -1));
}
writeFileSync(process.argv[2], `// Generated by node ${process.version} (Unicode ${process.versions.unicode}): the code points of /[\\p{L}\\p{N}]/u, letters and
// numbers, as ranges. Do not edit; made again by gen-words.mjs beside this.

///|
let word_ranges : FixedArray[Int] = [${out.map((x) => `0x${x.toString(16)}`).join(", ")}]
`);
