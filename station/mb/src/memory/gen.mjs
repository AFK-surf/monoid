// Writes tables.mbt (node station/mb/src/memory/gen.mjs station/mb/src/memory/tables.mbt) from this node's Unicode
// properties: the code points of /[\p{L}\p{N}]/u, what a station's name keeps of itself in a file's name
// (test/reference/memory-merge.ts `stationTag`).
import { writeFileSync } from "node:fs";
const ranges = (re) => {
  const out = [];
  let start = -1;
  for (let c = 0; c <= 0x110000; c++) {
    const ok = c <= 0x10ffff && !(c >= 0xd800 && c <= 0xdfff) && re.test(String.fromCodePoint(c));
    if (ok && start < 0) start = c;
    if (!ok && start >= 0) out.push([start, c - 1]), (start = -1);
  }
  return out;
};
const fmt = (xs) => xs.map((x) => `0x${x.toString(16)}`).join(", ");
const out = `// Generated by node ${process.version} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}): the code points of
// /[\\p{L}\\p{N}]/u as ranges, first and last of each. Do not edit; made again with the node the station runs, by gen.mjs
// beside this.

///|
let word_ranges : FixedArray[Int] = [${fmt(ranges(/[\p{L}\p{N}]/u).flat())}]
`;
writeFileSync(process.argv[2], out);
