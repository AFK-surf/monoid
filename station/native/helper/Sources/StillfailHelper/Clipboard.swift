// The Mac's clipboard for a view a person drives (docs/remote-screens.md `clipboard`, ScreenView.swift's messages 4–6):
// set from the viewer and pasted with ⌘V, watched while the view asks (its changeCount looked at every half a second,
// on the main queue, nothing else read until it changes), and a file shown in Finder. Text first, else a picture as
// PNG (from PNG or TIFF), each within its bound; what this view set itself is not said back to it, nor what was said
// last (a viewer on a device of the same Apple Account puts what it was told on its own clipboard, which Universal
// Clipboard brings back here as a change: said again, it would go round for good). A copy an app marked
// (nspasteboard.org: a password manager's concealed one, a transient or a program's own) is said with its mark (message
// 12), and one set from the viewer with a mark is written with it, so this Mac's clipboard managers leave it out.
import AppKit
import CoreGraphics
import Foundation

final class Clipboard {
  /// What a view carries each way at most (station/src/screens/source.ts CLIP_TEXT_MAX, CLIP_PNG_MAX).
  static let textMax = 1024 * 1024
  static let pngMax = 8 * 1024 * 1024
  /// How often the changeCount is looked at while watched.
  static let interval: TimeInterval = 0.5

  let channel: Channel
  let input: ScreenInput
  private var timer: DispatchSourceTimer?
  /// The changeCount last seen (or set here): a change after it is a copy made on the Mac.
  private var seen = 0
  /// What was last said or set (its type, its bytes): the same again is no copy made on the Mac.
  private var last: Data?

  /// nspasteboard.org's marks, by their code on the wires (1 concealed, 2 transient, 3 auto): the types that say
  /// each (the first is the one written), the strictest found first when read (transient, concealed, auto).
  static let marks: [(code: UInt8, types: [String])] = [
    (2, ["org.nspasteboard.TransientType", "de.petermaurer.TransientPasteboardType"]),
    (1, ["org.nspasteboard.ConcealedType", "com.agilebits.onepassword"]),
    (3, ["org.nspasteboard.AutoGeneratedType", "com.typeit4me.clipping", "Pasteboard generator type"]),
  ]
  /// What Universal Clipboard says of a copy another Apple device made (a promise of its data, not yet here).
  static let remote = "com.apple.is-remote-clipboard"

  /// The mark of a clipboard with these types: 0 none.
  static func mark(of types: [String]) -> UInt8 {
    let have = Set(types)
    for m in marks where m.types.contains(where: have.contains) { return m.code }
    return 0
  }

  /// The type a mark is written as (none for 0 or an unknown code).
  static func type(of mark: UInt8) -> String? {
    marks.first { $0.code == mark }?.types.first
  }

  /// Message 4's flags: whether to paste, and the mark (bits 1..2).
  static func flags(_ byte: UInt8) -> (paste: Bool, mark: UInt8) {
    (byte & 1 == 1, (byte >> 1) & 3)
  }

  init(channel: Channel, input: ScreenInput) {
    self.channel = channel
    self.input = input
  }

  /// Message 4: flags (bit 0: paste, bits 1..2 its mark), type (1 text, 2 PNG), the bytes. Set after the input before
  /// it, on its queue, then ⌘V where the focus is.
  func set(_ payload: Data) {
    guard payload.count >= 3 else { return }
    let bytes = [UInt8](payload)
    let (paste, mark) = Clipboard.flags(bytes[0])
    let type = bytes[1]
    let body = payload.subdata(in: payload.startIndex + 2..<payload.endIndex)
    input.queue.async {
      let done = DispatchQueue.main.sync { () -> Bool in
        let board = NSPasteboard.general
        switch type {
        case 1:
          guard body.count <= Clipboard.textMax, let text = String(data: body, encoding: .utf8) else { return false }
          board.clearContents()
          board.setString(text, forType: .string)
        case 2:
          guard body.count <= Clipboard.pngMax, let image = NSBitmapImageRep(data: body) else { return false }
          board.clearContents()
          board.setData(body, forType: .png)
          // Apps that read only TIFF (older ones) find it too.
          if let tiff = image.tiffRepresentation { board.setData(tiff, forType: .tiff) }
        default:
          return false
        }
        // (its mark as an empty item of its type: what clipboard managers look for)
        if let marked = Clipboard.type(of: mark) { board.setData(Data(), forType: NSPasteboard.PasteboardType(marked)) }
        self.seen = board.changeCount
        self.last = Data([type]) + body
        return true
      }
      if done && paste { self.input.paste() }
    }
  }

  /// Message 5: watched (1) or not (0).
  func watch(_ payload: Data) {
    let on = payload.first == 1
    DispatchQueue.main.async {
      self.timer?.cancel()
      self.timer = nil
      guard on else { return }
      // What it holds now is not a copy made while watched.
      self.seen = NSPasteboard.general.changeCount
      let timer = DispatchSource.makeTimerSource(queue: .main)
      timer.schedule(deadline: .now() + Clipboard.interval, repeating: Clipboard.interval, leeway: .milliseconds(100))
      timer.setEventHandler { [weak self] in self?.look() }
      timer.resume()
      self.timer = timer
    }
  }

  func stop() {
    DispatchQueue.main.async {
      self.timer?.cancel()
      self.timer = nil
    }
  }

  /// Message 6: the path, shown selected in Finder.
  func reveal(_ payload: Data) {
    guard let path = String(data: payload, encoding: .utf8), path.hasPrefix("/") else { return }
    DispatchQueue.main.async {
      let url = URL(fileURLWithPath: path)
      if FileManager.default.fileExists(atPath: path) {
        NSWorkspace.shared.activateFileViewerSelecting([url])
      } else {
        NSWorkspace.shared.open(url.deletingLastPathComponent())
      }
    }
  }

  /// The clipboard changed since last seen: what it holds now, said as message 5 (type, bytes), or 12 with its mark.
  /// Its types are looked at first (which asks nothing of macOS's privacy prompt); what Universal Clipboard brought from
  /// another Apple device is not said (the viewer's own device most often: said back, it would go round); what changed
  /// while it was read is read again at the next look.
  private func look() {
    let board = NSPasteboard.general
    let count = board.changeCount
    guard count != seen else { return }
    let types = (board.types ?? []).map(\.rawValue)
    if types.contains(Clipboard.remote) {
      seen = count
      return
    }
    let mark = Clipboard.mark(of: types)
    var said: Data?
    if let text = board.string(forType: .string), !text.isEmpty {
      let data = Data(text.utf8)
      if data.count <= Clipboard.textMax { said = Data([1]) + data }
    } else {
      var png = board.data(forType: .png)
      if png == nil, let tiff = board.data(forType: .tiff), let image = NSBitmapImageRep(data: tiff) {
        png = image.representation(using: .png, properties: [:])
      }
      if let png, !png.isEmpty, png.count <= Clipboard.pngMax { said = Data([2]) + png }
    }
    guard board.changeCount == count else { return }
    seen = count
    if let said { say(said, mark: mark) }
  }

  /// Message 5 (type, bytes) or 12 (mark, type, bytes), unless it is what was last said or set.
  private func say(_ what: Data, mark: UInt8) {
    guard what != last else { return }
    last = what
    if mark == 0 { channel.send(5, what) } else { channel.send(12, Data([mark]) + what) }
  }
}
